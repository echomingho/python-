#程式練習:驗證使用者輸入的合法性
# - 您的使用者名稱不能超過 12 個字元
# - 您的使用者名稱不能包含空格
# - 您的使用者名稱不能包含數字
# - 如果都符合的話,顯示: 歡迎 + 使用者名稱

print ("您的使用者名稱不能超過 12 個字元" , "您的使用者名稱不能包含空格" ,  "您的使用者名稱不能包含數字" )

user_name = input("請輸入您的使用者名稱:")

if len(user_name) > 12:
    print("您輸入的字元超過12個字")
elif " " in user_name:
    print("您的使用者名稱不可使用空格")
elif not user_name.isalpha(): #isalpha這個函數是指在使用者輸入的字串裡尋找不是英文字的其他字元
    print("您的使用者名稱不可包含數字")
else:
    print("歡迎:",user_name,"您的加入")